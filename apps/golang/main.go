func main() {
	list := flag.Bool("list", false, "list the available banner words and exit")
	border := flag.Bool("border", false, "draw a border around the banner")
	flag.Usage = usage
	flag.Parse()

	if *list {
		for _, name := range names() {
			fmt.Println(name)
		}
		return
	}

	args := flag.Args()
	if len(args) != 1 {
		usage()
		os.Exit(2)
	}

	art, ok := lookup(args[0])
	if !ok {
		fmt.Fprintf(os.Stderr, "banner: no banner for %q\n", args[0])
		fmt.Fprintf(os.Stderr, "available words: %s\n", strings.Join(names(), ", "))
		os.Exit(1)
	}

	if *border {
		art = withBorder(art)
	}

	fmt.Println(art)
}

// withBorder wraps art in a box drawn with - and | characters.
func withBorder(art string) string {
	lines := strings.Split(art, "\n")

	// Find the widest line (measured in runes, since the art can be unicode).
	width := 0
	for _, line := range lines {
		if n := len([]rune(line)); n > width {
			width = n
		}
	}

	top := "+" + strings.Repeat("-", width+2) + "+"

	var b strings.Builder
	b.WriteString(top + "\n")
	for _, line := range lines {
		pad := width - len([]rune(line))
		b.WriteString("| " + line + strings.Repeat(" ", pad) + " |\n")
	}
	b.WriteString(top)
	return b.String()
}

// lookup finds the art for a word
func lookup(word string) (string, bool) {
	img, ok := images[strings.ToLower(strings.TrimSpace(word))]
	if !ok {
		return "", false
	}
	return strings.Trim(img, "\n"), true
}

// names returns the banner words in a stable, sorted order.
func names() []string {
	out := make([]string, 0, len(images))
	for name := range images {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

func usage() {
	prog := filepath.Base(os.Args[0])
	fmt.Fprintf(os.Stderr, "usage: %s [-list] <word>\n\n", prog)
	fmt.Fprintf(os.Stderr, "Prints an ASCII banner matching <word>.\n\nwords:\n")
	for _, name := range names() {
		fmt.Fprintf(os.Stderr, "  %s\n", name)
	}
	fmt.Fprintf(os.Stderr, "\nflags:\n")
	flag.PrintDefaults()
}
