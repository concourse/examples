// colors maps a color name to its ANSI SGR foreground code.
var colors = map[string]string{
	"red":   "31",
	"green": "32",
	"blue":  "34",
}

func main() {
	list := flag.Bool("list", false, "list the available banner words and exit")
	color := flag.String("color", "", "print the banner in a color: red, green, or blue")
	flag.Usage = usage
	flag.Parse()

	if *list {
		for _, name := range names() {
			fmt.Println(name)
		}
		return
	}

	args := flag.Args()
	if len(args) != 1 {
		usage()
		os.Exit(2)
	}

	art, ok := lookup(args[0])
	if !ok {
		fmt.Fprintf(os.Stderr, "banner: no banner for %q\n", args[0])
		fmt.Fprintf(os.Stderr, "available words: %s\n", strings.Join(names(), ", "))
		os.Exit(1)
	}

	out, err := colorize(art, *color)
	if err != nil {
		fmt.Fprintf(os.Stderr, "banner: %v\n", err)
		os.Exit(1)
	}

	fmt.Println(out)
}

func colorize(art, color string) (string, error) {
	color = strings.ToLower(strings.TrimSpace(color))
	if color == "" {
		return art, nil
	}
	code, ok := colors[color]
	if !ok {
		return "", fmt.Errorf("unknown color %q (want red, green, or blue)", color)
	}
	return "\x1b[" + code + "m" + art + "\x1b[0m", nil
}

// lookup finds the art for a word
func lookup(word string) (string, bool) {
	img, ok := images[strings.ToLower(strings.TrimSpace(word))]
	if !ok {
		return "", false
	}
	return strings.Trim(img, "\n"), true
}

// names returns the banner words in a stable, sorted order.
func names() []string {
	out := make([]string, 0, len(images))
	for name := range images {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

func usage() {
	prog := filepath.Base(os.Args[0])
	fmt.Fprintf(os.Stderr, "usage: %s [-list] [-color] <word>\n\n", prog)
	fmt.Fprintf(os.Stderr, "Prints an ASCII banner matching <word>.\n\nwords:\n")
	for _, name := range names() {
		fmt.Fprintf(os.Stderr, "  %s\n", name)
	}
	fmt.Fprintf(os.Stderr, "\nflags:\n")
	flag.PrintDefaults()
}
